class PersonalTierFeedbackTests(unittest.IsolatedAsyncioTestCase):
    async def feedback(self, previous_tier=None, previous_date=None, suppressed=False, extra=()):
        row = NS(
            checkin_id=42, discord_id="123", medal_name="highest_tier_personal",
            medal_emoji="🏆", checkin_tier="T12",
            personal_previous_tier=previous_tier, personal_previous_date=previous_date,
        )
        message = NS(author=NS(id=999), add_reaction=AsyncMock(), reply=AsyncMock())
        saved = submission.SavedCheckin(42, NS(id=7, challenge_id=2, start=date(2026, 9, 7)))
        with patch.object(submission.medals, "update_medal_table"), patch.object(
            submission.medal_log, "get_medal_log", return_value=[row, *extra]
        ), patch.object(submission, "should_suppress_medal_announcements", return_value=suppressed):
            await submission.send_checkin_feedback(message, "T12", saved)
        return message

    async def test_first_record_uses_saved_owner_and_tier(self):
        message = await self.feedback()
        message.reply.assert_awaited_once_with(
            "<@123> earned 🏆 __**Highest Ever Personal Tier**__ with a T12 check-in!"
        )
        message.add_reaction.assert_any_await("🏆")
        self.assertNotIn("999", message.reply.call_args.args[0])

    async def test_previous_record_includes_tier_and_date(self):
        message = await self.feedback("T9", date(2025, 1, 2))
        message.reply.assert_awaited_once_with(
            "<@123> earned 🏆 __**Highest Ever Personal Tier**__ with a T12 check-in, "
            "exceeding their T9 check-in on January 2, 2025!"
        )

    async def test_personal_record_is_immediate_but_other_medals_stay_silent(self):
        other = NS(checkin_id=42, discord_id="123", medal_name="highest_tier_week", medal_emoji="💪")
        message = await self.feedback("T9", date(2025, 1, 2), suppressed=True, extra=[other])
        message.reply.assert_awaited_once()
        self.assertIn("Highest Ever Personal Tier", message.reply.call_args.args[0])
        self.assertNotIn("Highest Weekly Tier", message.reply.call_args.args[0])
        message.add_reaction.assert_any_await("🏆")
        message.add_reaction.assert_any_await("💪")

    async def test_personal_record_and_other_medals_share_one_reply(self):
        other = NS(
            checkin_id=42, discord_id="123", medal_name="highest_tier_week", medal_emoji="💪",
            stolen_checkin_challenger_name=None, stolen_discord_id=None,
        )
        message = await self.feedback(extra=[other])
        message.reply.assert_awaited_once()
        self.assertIn("Highest Ever Personal Tier", message.reply.call_args.args[0])
        self.assertIn("Highest Weekly Tier", message.reply.call_args.args[0])
        self.assertNotIn("stole", message.reply.call_args.args[0])

    async def test_another_users_record_is_not_announced(self):
        other = NS(checkin_id=99, discord_id="456", medal_name="highest_tier_personal", medal_emoji="🏆")
        message = await self.feedback(extra=[other])
        self.assertNotIn("456", message.reply.call_args.args[0])

    def test_personal_medal_cannot_be_stolen(self):
        self.assertIn("highest_tier_personal", NON_STEALABLE_MEDALS)


@unittest.skipUnless(os.environ.get("TEST_DB_CONNECT_STRING"), "Set TEST_DB_CONNECT_STRING to run PostgreSQL tests")
class PersonalTierPostgresTests(unittest.TestCase):
    """Real SQL against temporary tables; seed data is never modified."""

    def setUp(self):
        import psycopg
        from psycopg.rows import namedtuple_row
        self.conn = psycopg.connect(os.environ["TEST_DB_CONNECT_STRING"], row_factory=namedtuple_row)
        self.addCleanup(self.conn.close)
        self.addCleanup(self.conn.rollback)
        self.conn.execute("""
            CREATE TEMP TABLE challengers (id int PRIMARY KEY, name text, discord_id text, tz text);
            CREATE TEMP TABLE challenges (id int PRIMARY KEY, name text);
            CREATE TEMP TABLE challenge_weeks (
                id int PRIMARY KEY, challenge_id int, start date, "end" date, bye_week bool DEFAULT false
            );
            CREATE TEMP TABLE checkins (
                id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                challenger int, name text, tier text, time timestamptz,
                tz text DEFAULT 'America/New_York', challenge_week_id int, text text, day_of_week text
            );
            CREATE TEMP TABLE challenger_challenges (challenger_id int, challenge_id int, mulligan int);
            CREATE TEMP TABLE medals (
                id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                challenger_id int, medal text, challenge_id int, challenge_week_id int,
                checkin_id int, steal int, emoji text, created_at timestamp DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (medal, checkin_id)
            );
            INSERT INTO challengers VALUES (1, 'First', '123', 'America/New_York'), (2, 'Second', '456', 'Asia/Tokyo');
            INSERT INTO challenges VALUES (1, 'Previous challenge'), (2, 'New challenge');
            INSERT INTO challenge_weeks VALUES
                (1, 1, '2025-01-01', '2025-01-07', false),
                (2, 2, '2026-01-01', '2026-01-07', false),
                (3, 2, '2026-01-08', '2026-01-14', true);
        """)

        def fetchall(query, args=None):
            return self.conn.execute(query, args).fetchall()

        def transaction(fn):
            with self.conn.cursor() as cursor:
                return fn(self.conn, cursor)

        for target, replacement in (
            ("medals.fetchall", fetchall),
            ("medals.fetchone", lambda query, args=None: self.conn.execute(query, args).fetchone()),
            ("personal_records.fetchall", fetchall),
            ("medal_log.fetchall", fetchall),
            ("medals.with_psycopg", transaction),
            ("slash_commands.testpodium.fetchall", fetchall),
        ):
            patcher = patch(target, side_effect=replacement)
            patcher.start()
            self.addCleanup(patcher.stop)

    def checkin(self, checkin_id, tier, when, week=2, challenger=1, tz="America/New_York"):
        self.conn.execute(
            "INSERT INTO checkins (id, challenger, name, tier, time, tz, challenge_week_id) "
            "VALUES (%s, %s, %s, %s, %s, %s, %s)",
            [checkin_id, challenger, f"User {challenger}", tier, when, tz, week],
        )

    def records(self, week=2):
        return medals.highest_tier_personal(week, execute=True)

    def persist(self, week=2):
        records = self.records(week)
        medals.insert_medals([row._asdict() for row in records], 2 if week != 1 else 1)
        return medal_log.get_medal_log(week)

    def test_first_checkin_sets_record_even_at_tier_zero(self):
        self.checkin(1, "T0", "2026-01-01T12:00Z")
        self.assertEqual([row.checkin_id for row in self.records()], [1])
        row = self.persist()[0]
        self.assertIsNone(row.personal_previous_tier)
        self.assertIsNone(row.personal_previous_date)

    def test_history_without_medal_rows_is_baseline_across_challenges(self):
        self.checkin(1, "T10", "2025-01-02T12:00Z", week=1)
        self.checkin(2, "T9", "2026-01-01T12:00Z")
        self.checkin(3, "T10", "2026-01-02T12:00Z")
        self.checkin(4, "T11", "2026-01-03T12:00Z")
        self.assertEqual([row.checkin_id for row in self.records()], [4])
        self.assertEqual(self.persist()[0].personal_previous_tier, "T10")

    def test_numeric_comparison_ties_and_lower_tiers(self):
        for checkin_id, tier in enumerate(("T2", "T9", "T10", "T10", "T3", "T12"), 1):
            self.checkin(checkin_id, tier, f"2026-01-0{checkin_id}T12:00Z")
        self.assertEqual([row.checkin_id for row in self.records()], [1, 2, 3, 6])
        previous = {row.checkin_id: row.personal_previous_tier for row in self.persist()}
        self.assertEqual(previous, {1: None, 2: "T2", 3: "T9", 6: "T10"})

    def test_records_are_per_participant(self):
        self.checkin(1, "T20", "2025-01-01T12:00Z", week=1)
        self.checkin(2, "T1", "2026-01-01T12:00Z", challenger=2)
        self.assertEqual([(row.challenger_id, row.tier) for row in self.records()], [(2, "T1")])

    def test_previous_date_uses_record_checkins_original_timezone(self):
        self.checkin(1, "T9", "2025-01-02T01:30Z", week=1, tz="America/Los_Angeles")
        self.checkin(2, "T10", "2026-01-01T12:00Z", tz="Asia/Tokyo")
        row = self.persist()[0]
        self.assertEqual(row.personal_previous_date, date(2025, 1, 1))

    def test_tied_previous_best_uses_date_it_was_first_achieved(self):
        self.checkin(1, "T9", "2025-01-02T12:00Z", week=1)
        self.checkin(2, "T9", "2025-01-03T12:00Z", week=1)
        self.checkin(3, "T10", "2026-01-01T12:00Z")
        self.assertEqual(self.persist()[0].personal_previous_date, date(2025, 1, 2))

    def test_later_checkins_cannot_change_previous_record_of_earlier_award(self):
        self.checkin(1, "T9", "2025-01-01T12:00Z", week=1)
        self.checkin(2, "T10", "2026-01-01T12:00Z")
        self.checkin(3, "T15", "2026-01-02T12:00Z")
        self.assertEqual(
            {row.checkin_id: row.personal_previous_tier for row in self.persist()},
            {2: "T9", 3: "T10"},
        )

    def test_automatic_mulligans_are_excluded_from_records_and_history(self):
        self.checkin(1, "T1", "2025-01-01T12:00Z", week=1)
        self.checkin(2, "T1", "2026-01-01T12:00Z")
        self.conn.execute("INSERT INTO challenger_challenges VALUES (1, 1, 1), (1, 2, 2)")
        self.checkin(3, "T1", "2026-01-02T12:00Z")
        self.assertEqual([row.checkin_id for row in self.records()], [3])
        self.assertIsNone(self.persist()[0].personal_previous_tier)

    def test_award_storage_is_idempotent(self):
        self.checkin(1, "T4", "2026-01-01T12:00Z")
        self.persist()
        self.persist()
        self.assertEqual(self.conn.execute("SELECT count(*) FROM medals").fetchone()[0], 1)
        self.assertIsNone(self.conn.execute("SELECT steal FROM medals").fetchone().steal)

    def test_bye_week_and_same_timestamp_order_are_deterministic(self):
        self.checkin(1, "T4", "2026-01-08T12:00Z", week=3)
        self.checkin(2, "T5", "2026-01-08T12:00Z", week=3)
        self.checkin(3, "T5", "2026-01-08T12:00Z", week=3)
        self.assertEqual([row.checkin_id for row in self.records(3)], [1, 2])

    def test_uncheckin_restores_previous_best_for_next_checkin(self):
        self.checkin(1, "T9", "2025-01-01T12:00Z", week=1)
        self.checkin(2, "T15", "2026-01-01T12:00Z")
        self.persist()
        self.conn.execute("DELETE FROM medals WHERE checkin_id = 2")
        self.conn.execute("DELETE FROM checkins WHERE id = 2")
        self.checkin(3, "T10", "2026-01-02T12:00Z")
        self.assertEqual(self.persist()[0].personal_previous_tier, "T9")

    def test_roundup_keeps_personal_records_for_both_users(self):
        self.checkin(1, "T5", "2026-01-01T12:00Z")
        self.checkin(2, "T6", "2026-01-01T12:00Z", challenger=2)
        self.persist()
        standings = medals.get_current_week_medal_standings(2, 2)
        self.assertEqual({row.discord_id for row in standings}, {"123", "456"})

    def test_full_medal_pipeline_persists_personal_records_once(self):
        self.checkin(1, "T9", "2025-01-02T12:00Z", week=1)
        self.checkin(2, "T10", "2026-01-01T12:00Z")
        with patch("builtins.print"):
            medals.update_medal_table(2, 2)
            medals.update_medal_table(2, 2)
        personal = [row for row in medal_log.get_medal_log(2) if row.medal_name == "highest_tier_personal"]
        self.assertEqual(len(personal), 1)
        self.assertEqual(personal[0].personal_previous_tier, "T9")
        self.assertEqual(personal[0].medal_emoji, "🏆")

    def test_podium_preserves_multiple_personal_records_and_recipients(self):
        self.checkin(1, "T5", "2026-01-01T12:00Z")
        self.checkin(2, "T6", "2026-01-02T12:00Z")
        self.checkin(3, "T6", "2026-01-01T12:00Z", challenger=2)
        self.persist()
        rows = testpodium.get_final_medal_holders_per_week(2)
        counts = testpodium.collect_all_achievement_tags(rows)
        self.assertEqual(counts["highest_tier_personal"], {"123": 2, "456": 1})

    def test_invalid_tiers_are_not_personal_records_or_baselines(self):
        self.checkin(1, "invalid", "2025-01-01T12:00Z", week=1)
        self.checkin(2, "T-1", "2026-01-01T12:00Z")
        self.checkin(3, "T3", "2026-01-02T12:00Z")
        self.assertEqual([row.checkin_id for row in self.records()], [3])
        self.assertIsNone(self.persist()[0].personal_previous_tier)

    def test_saved_calculator_checkin_earns_record_and_tie_does_not_repeat(self):
        self.checkin(1, "T9", "2025-01-02T12:00Z", week=1)
        self.conn.execute("INSERT INTO challenger_challenges VALUES (1, 2, NULL)")
        self.conn.execute("ALTER TABLE checkins ALTER COLUMN id RESTART WITH 1000")
        challenger = NS(id=1, name="First", tz="America/New_York")
        week = NS(id=2, challenge_id=2, start=date(2026, 1, 1))

        def transaction(fn):
            with self.conn.cursor() as cursor:
                return fn(self.conn, cursor)

        with patch.object(submission, "challenger_by_discord_id", return_value=challenger), patch.object(
            submission, "get_current_challenge_week", return_value=week
        ), patch.object(submission, "with_psycopg", side_effect=transaction), patch.object(
            submission, "fetchone", side_effect=lambda sql, args: self.conn.execute(sql, args).fetchone()
        ), patch.object(submission, "should_suppress_medal_announcements", return_value=True), patch("builtins.print"):
            saved = submission.save_checkin("T12 check-in", "T12", 123, require_active_member=True)
            message = NS(author=NS(id=999), add_reaction=AsyncMock(), reply=AsyncMock())
            asyncio.run(submission.send_checkin_feedback(message, "T12", saved))
            message.reply.assert_awaited_once_with(
                "<@123> earned 🏆 __**Highest Ever Personal Tier**__ with a T12 check-in, "
                "exceeding their T9 check-in on January 2, 2025!"
            )
            tied = submission.save_checkin("T12 check-in", "T12", 123, require_active_member=True)
            tied_message = NS(add_reaction=AsyncMock(), reply=AsyncMock())
            asyncio.run(submission.send_checkin_feedback(tied_message, "T12", tied))
            tied_message.reply.assert_not_awaited()
            self.assertNotIn("🏆", [call.args[0] for call in tied_message.add_reaction.await_args_list])


